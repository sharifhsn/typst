//! Generated inverse symbol tables: Unicode codepoint → idiomatic Typst.
//!
//! These tables are the *inverse* of the mapping the DOCX exporter
//! (`crates/typst-docx`) and the Typst compiler use when generating OMML from
//! Typst math. The exporter turns a Typst symbol name (`alpha`, `times`, `<=`)
//! into a Unicode codepoint (α, ×, ≤) via the `codex` crate's `sym.txt`, and
//! italicises variables by remapping ASCII/Greek letters to their Plane-1
//! Mathematical-Alphanumeric codepoints (`x` → 𝑥 U+1D465). To recover clean,
//! paste-ready Typst we undo both steps.
//!
//! * [`symbol_name`] maps a standalone symbol codepoint back to the shortest
//!   idiomatic Typst token (preferring shorthands like `<=`, `->`, `!=`).
//! * [`math_alpha`] maps a Plane-1 styled letter/digit back to its base
//!   character plus the [`Style`] wrapper that produced it, so `𝐀` becomes
//!   `bold(A)` and a plain italic `𝑥` becomes a bare `x` (Typst italicises math
//!   variables by default — wrapping them in `upright(..)` is exactly the
//!   pandoc bug this tool avoids).
//!
//! Both tables were derived mechanically from `codex` 0.3.0's `sym.txt` and the
//! Unicode Mathematical Alphanumeric Symbols block; see the crate's build notes.

/// The style a Plane-1 math-alphanumeric glyph encodes. `Italic` is the Typst
/// default for a bare variable and therefore emits no wrapper.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Style {
    /// Default math italic — emit the base char bare (no wrapper).
    Italic,
    Bold,
    /// Calligraphic / script — `cal(..)`.
    Cal,
    /// Fraktur — `frak(..)`.
    Frak,
    /// Blackboard bold / double-struck — `bb(..)`.
    Bb,
    Sans,
    SansBold,
    Mono,
}

